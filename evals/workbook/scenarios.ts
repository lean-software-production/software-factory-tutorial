export function createAuthoredWorkbookScenarioGateCheckpointRecorder(scenario: Pick<AuthoredWorkbookScenarioDescriptor, "id" | "gateCheckpoints">): AuthoredWorkbookScenarioGateCheckpointRecorder {
  const allowed = new Set((scenario.gateCheckpoints ?? []).map(validateGateCheckpointLabel));
  const captured: AuthoredWorkbookGateCheckpointLabel[] = [];
  return Object.freeze({
    get labels() { return Object.freeze([...captured]); },
    captureGateCheckpoint(label: AuthoredWorkbookGateCheckpointLabel) {
      const validated = validateGateCheckpointLabel(label);
      if (!allowed.has(validated)) throw new Error(`Scenario ${scenario.id} does not declare gate checkpoint '${validated}'.`);
      if (captured.includes(validated)) throw new Error(`Scenario ${scenario.id} captured duplicate gate checkpoint '${validated}'.`);
      captured.push(validated);
    }
  });
}

