function hasTrustedCalculatorBehavior(input: AuthoredWorkbookScenarioGateInput, source: string, options: { requireIntermediateMultiplyOnly?: boolean } = {}): boolean {
  const projection = input.facts.calculatorBehaviorProjection;
  if (!projection || projection.testStatus !== "passed") return false;
  if (projection.sourceSha256 !== sha256Text(source)) return false;
  if (projection.gitTree !== undefined && input.facts.calculatorTopCommitTree !== undefined && projection.gitTree !== input.facts.calculatorTopCommitTree) return false;
  const cases = new Map(projection.cases.map((entry) => [entry.input, entry.output]));
  if (cases.get("multiply 6 by 7") !== 42 || cases.get("divide 84 by 2") !== 42) return false;
  if (!hasCompletedMultiplyAndDivideRefactor(source)) return false;
  if (options.requireIntermediateMultiplyOnly) {
    const multiplyOnly = input.facts.calculatorBehaviorTimeline?.find((entry) => entry.label === "after-multiply-only");
    if (!multiplyOnly || multiplyOnly.testStatus !== "passed") return false;
    const intermediate = new Map(multiplyOnly.cases.map((entry) => [entry.input, entry.output]));
    if (intermediate.get("multiply 6 by 7") !== 42 || intermediate.has("divide 84 by 2")) return false;
  }
  return true;
}

function matchesStub(invocation: AuthoredCommandInvocationEvidence, expected: Partial<AuthoredCommandInvocationEvidence>): boolean {
  if (!invocation.accepted) return false;
  for (const [key, value] of Object.entries(expected) as Array<[keyof AuthoredCommandInvocationEvidence, unknown]>) {
    if (value !== undefined && invocation[key] !== value) return false;
  }
  return true;
}

