function hasExactTerminalLifecycle(input: AuthoredWorkbookScenarioGateInput, expected: readonly { blockSuffix: string; command: string }[]): boolean {
  const rawEvents = input.rawEvents;
  const submissionVersions = new Map<string, number>();
  const attemptVersions = new Map<string, number>();
  const eventIndexes = new Map<WorkbookTimelineRecord, number>();
  rawEvents.forEach((event, index) => {
    eventIndexes.set(event, index);
    if (event.type === "terminal-command-submitted") {
      const next = (submissionVersions.get(event.blockId) ?? 0) + 1;
      submissionVersions.set(event.blockId, next);
      attemptVersions.set(event.attemptId, next);
    }
  });

  let previousAcceptedIndex = -1;
  for (const wanted of expected) {
    const submissions = rawEvents.filter((event): event is Extract<WorkbookTimelineRecord, { type: "terminal-command-submitted" }> => event.type === "terminal-command-submitted" && event.blockId.endsWith(`--${wanted.blockSuffix}`));
    if (submissions.length !== 1) return false;
    const submitted = submissions[0]!;
    if (submitted.command.replace(/[\r\n]+$/, "") !== wanted.command) return false;
    const submittedIndex = eventIndexes.get(submitted)!;
    const version = attemptVersions.get(submitted.attemptId);
    if (!Number.isInteger(version) || version! < 1) return false;

    const finishedRows = rawEvents.filter((event): event is Extract<WorkbookTimelineRecord, { type: "terminal-command-finished" }> => event.type === "terminal-command-finished" && event.attemptId === submitted.attemptId);
    if (finishedRows.length !== 1) return false;
    const finished = finishedRows[0]!;
    const finishedIndex = eventIndexes.get(finished)!;
    if (finishedIndex <= submittedIndex || finished.exitStatus !== 0) return false;

    const acceptedRows = rawEvents.filter((event): event is Extract<WorkbookTimelineRecord, { type: "attempt_accepted" }> => event.type === "attempt_accepted" && event.kind === "terminal" && event.attemptId === submitted.attemptId && event.lessonId === submitted.lessonId && event.blockId === submitted.blockId);
    if (acceptedRows.length !== 1) return false;
    const accepted = acceptedRows[0]!;
    const acceptedIndex = eventIndexes.get(accepted)!;
    if (acceptedIndex <= finishedIndex || acceptedIndex <= previousAcceptedIndex || accepted.version !== version) return false;
    if (publicTerminalRevision(input.trace, submitted.blockId) !== version) return false;
    previousAcceptedIndex = acceptedIndex;
  }
  return true;
}

function publicTerminalRevision(trace: AuthoredWorkbookEvalTrace, blockId: string): number | undefined {
  let revision: number | undefined;
  for (const recorded of trace.publicStates) {
    const block = recorded.state.progress.blocks.find((candidate) => candidate.id === blockId);
    if (block && Number.isInteger(block.terminalRevision)) revision = block.terminalRevision;
  }
  return revision;
}

