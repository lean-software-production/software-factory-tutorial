function validatePrerequisiteSeedCatalog(catalog: Record<string, readonly string[]>): void {
  const ids = new Set<string>();
  for (const [id, files] of Object.entries(catalog)) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id) || ids.has(id)) throw new Error("Authored prerequisite seed IDs must be unique and safe.");
    ids.add(id);
    if (!Array.isArray(files) || files.length === 0 || files.length > 64) throw new Error(`Authored prerequisite seed '${id}' needs a bounded file manifest.`);
    const seen = new Set<string>();
    for (const file of files) {
      if (typeof file !== "string" || file.length === 0 || file.startsWith("/") || file.includes("\\") || file.includes("\0")) throw new Error(`Unsafe prerequisite seed file in '${id}'.`);
      const parts = file.split("/");
      if (parts.some((part) => part === "" || part === "." || part === ".." || [".tmp", ".tutorial", ".git", "node_modules", ".DS_Store"].includes(part))) throw new Error(`Unsafe prerequisite seed file in '${id}'.`);
      if (file.endsWith(".jsonl")) throw new Error(`Raw event files cannot be prerequisite seed files in '${id}'.`);
      if (seen.has(file)) throw new Error(`Duplicate prerequisite seed file '${file}' in '${id}'.`);
      seen.add(file);
    }
  }
}
