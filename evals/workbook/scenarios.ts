function finalizeScenario<T extends AuthoredWorkbookScenarioDescriptor>(scenario: T): T {
  const copy = {
    ...scenario,
    selection: deepFreeze(structuredClone(scenario.selection)),
    ...(scenario.prerequisiteOverlay === undefined ? {} : { prerequisiteOverlay: deepFreeze({ ...scenario.prerequisiteOverlay, files: freezeStrings(scenario.prerequisiteOverlay.files) }) }),
    artifactAllowlist: freezeStrings(scenario.artifactAllowlist),
    ...(scenario.runnerPrivate === undefined ? {} : { runnerPrivate: freezeRunnerPrivateDeclaration(scenario.runnerPrivate) }),
    ...(scenario.gateCheckpoints === undefined ? {} : { gateCheckpoints: freezeGateCheckpointLabels(scenario.gateCheckpoints) }),
    expectedModelCalls: freezeExpectedCalls(scenario.expectedModelCalls),
    expectedModelCallDerivation: freezeStrings(scenario.expectedModelCallDerivation),
    criteria: Object.freeze(scenario.criteria.map((entry) => Object.freeze({ ...entry })))
  } as T;
  return Object.freeze(copy);
}

function validateScenarioCatalog(scenarios: readonly AuthoredWorkbookScenarioDescriptor[]): void {
  const ids = new Set<string>();
  for (const scenario of scenarios) {
    if (!scenario.id || ids.has(scenario.id)) throw new Error("Authored workbook scenario IDs must be unique and nonempty.");
    ids.add(scenario.id);
    validateSelectionShape(scenario.selection);
    const artifactPaths = scenario.artifactAllowlist.map(assertSafeScenarioPath);
    if (new Set(artifactPaths).size !== artifactPaths.length) throw new Error(`Scenario ${scenario.id} has duplicate artifact paths.`);
    if (scenario.runnerPrivate !== undefined) validateRunnerPrivateDeclaration(scenario.id, scenario.runnerPrivate);
    if (scenario.gateCheckpoints !== undefined) {
      const labels = scenario.gateCheckpoints.map(validateGateCheckpointLabel);
      if (new Set(labels).size !== labels.length) throw new Error(`Scenario ${scenario.id} has duplicate gate checkpoint labels.`);
    }
    if (scenario.prerequisiteOverlay !== undefined) {
      if (scenario.prerequisiteOverlay.workspaceId !== "refactor-line") throw new Error(`Scenario ${scenario.id} declares an unsupported prerequisite overlay workspace.`);
      if (scenario.prerequisiteOverlay.sourceRoot !== resolve(prerequisiteRoot, scenario.prerequisiteOverlay.id)) throw new Error(`Scenario ${scenario.id} prerequisite overlay must use the canonical seed root.`);
      if (!Object.hasOwn(AUTHORED_WORKBOOK_PREREQUISITE_SEED_FILES, scenario.prerequisiteOverlay.id)) throw new Error(`Scenario ${scenario.id} declares an unknown prerequisite overlay.`);
      if (JSON.stringify([...scenario.prerequisiteOverlay.files]) !== JSON.stringify([...(AUTHORED_WORKBOOK_PREREQUISITE_SEED_FILES as Record<string, readonly string[]>)[scenario.prerequisiteOverlay.id]!])) throw new Error(`Scenario ${scenario.id} prerequisite overlay manifest does not match its seed catalog.`);
    }
    if (scenario.expectedModelCalls.total !== scenario.expectedModelCalls.mainTutor + scenario.expectedModelCalls.practiceCoach + scenario.expectedModelCalls.judge) throw new Error(`Scenario ${scenario.id} has an invalid model-call total.`);
    if (scenario.expectedModelCalls.judge !== 1) throw new Error(`Scenario ${scenario.id} must budget exactly one Judge call.`);
    if (scenario.stubLessonNumber !== undefined && (scenario.stubLessonNumber < 2 || scenario.stubLessonNumber > 13)) throw new Error(`Scenario ${scenario.id} has an invalid stub lesson number.`);
    const criterionIds = new Set<string>();
    for (const criterion of scenario.criteria) {
      if (!criterion.id || criterionIds.has(criterion.id)) throw new Error(`Scenario ${scenario.id} has duplicate or empty criterion IDs.`);
      criterionIds.add(criterion.id);
    }
  }
}

function validateSelectionShape(selection: AuthoredCurriculumSliceSelection): void {
  if (!selection.parts.length) throw new Error("Scenario selection must include at least one part.");
  for (const part of selection.parts) {
    if (!part.id || !part.lessons.length) throw new Error("Scenario selection parts and lessons must be nonempty.");
    for (const lesson of part.lessons) if (!lesson.id) throw new Error("Scenario lesson selection ID must be nonempty.");
  }
}

function assertSafeScenarioPath(file: string): string {
  assertSafeRelativePath(file);
  if (isRawEventArtifactPath(file)) throw new Error("Raw event files are not public scenario artifacts.");
  return file;
}

function assertSafePrivateScenarioPath(file: string): string {
  assertSafeRelativePath(file);
  return file;
}

function assertSafePrivateScenarioPrefix(prefix: string): string {
  assertSafeRelativePath(prefix.endsWith("/") ? prefix.slice(0, -1) : prefix);
  if (!prefix.endsWith("/")) throw new Error("Private scenario path prefixes must end with '/'.");
  return prefix;
}

function assertSafeRelativePath(value: string): void {
  if (typeof value !== "string" || !value || value.startsWith("/") || value.includes("\0") || value.includes("\\") || value.split("/").some((part) => part === "" || part === "." || part === "..")) throw new Error("Unsafe scenario relative path.");
}

function validateGateCheckpointLabel(label: string): AuthoredWorkbookGateCheckpointLabel {
  if (!(AUTHORED_WORKBOOK_GATE_CHECKPOINT_LABELS as readonly string[]).includes(label)) throw new Error(`Unknown authored workbook gate checkpoint label: ${label}`);
  return label as AuthoredWorkbookGateCheckpointLabel;
}

function validateRunnerPrivateDeclaration(scenarioId: string, declaration: AuthoredWorkbookScenarioRunnerPrivateDeclaration): void {
  const workspaceFiles = declaration.gateEvidence.workspaceFiles.map(assertSafePrivateScenarioPath);
  if (new Set(workspaceFiles).size !== workspaceFiles.length) throw new Error(`Scenario ${scenarioId} has duplicate private gate evidence files.`);
  const workspacePrefixes = declaration.gateEvidence.workspacePathPrefixes.map(assertSafePrivateScenarioPrefix);
  if (new Set(workspacePrefixes).size !== workspacePrefixes.length) throw new Error(`Scenario ${scenarioId} has duplicate private gate evidence prefixes.`);
  const mutationFiles = declaration.mutationAllowlist.learnerWorkspaceFiles.map(assertSafePrivateScenarioPath);
  if (new Set(mutationFiles).size !== mutationFiles.length) throw new Error(`Scenario ${scenarioId} has duplicate private mutation files.`);
  const mutationPrefixes = declaration.mutationAllowlist.learnerWorkspacePathPrefixes.map(assertSafePrivateScenarioPrefix);
  if (new Set(mutationPrefixes).size !== mutationPrefixes.length) throw new Error(`Scenario ${scenarioId} has duplicate private mutation prefixes.`);
}

function freezeRunnerPrivateDeclaration(declaration: AuthoredWorkbookScenarioRunnerPrivateDeclaration): AuthoredWorkbookScenarioRunnerPrivateDeclaration {
  return deepFreeze({
    gateEvidence: {
      workspaceFiles: freezeStrings(declaration.gateEvidence.workspaceFiles),
      workspacePathPrefixes: freezeStrings(declaration.gateEvidence.workspacePathPrefixes),
      ...(declaration.gateEvidence.commandStubInvocations === true ? { commandStubInvocations: true as const } : {}),
      ...(declaration.gateEvidence.rawWorkbookTimeline === true ? { rawWorkbookTimeline: true as const } : {})
    },
    mutationAllowlist: {
      learnerWorkspaceFiles: freezeStrings(declaration.mutationAllowlist.learnerWorkspaceFiles),
      learnerWorkspacePathPrefixes: freezeStrings(declaration.mutationAllowlist.learnerWorkspacePathPrefixes)
    }
  });
}

function freezeGateCheckpointLabels(labels: readonly AuthoredWorkbookGateCheckpointLabel[]): readonly AuthoredWorkbookGateCheckpointLabel[] {
  return Object.freeze(labels.map(validateGateCheckpointLabel));
}

function deepFreeze<T>(value: T): T {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value as Record<string, unknown>)) deepFreeze(child);
  }
  return value;
}

function freezeExpectedCalls(input: Omit<AuthoredWorkbookScenarioExpectedModelCalls, "total">): AuthoredWorkbookScenarioExpectedModelCalls {
  const total = input.mainTutor + input.practiceCoach + input.judge;
  return Object.freeze({ ...input, total });
}

function freezeStrings(values: readonly string[]): readonly string[] {
  return Object.freeze([...values]);
}

